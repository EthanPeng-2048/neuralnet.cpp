# ── 客户端 ────────────────────────────────────────────────
client = OpenAI(base_url=BASE_URL, api_key=API_KEY, timeout=120)


def make_prompt(topic: str, variation_idx: int) -> str:
    variation = {
        0: "用一句完整的话阐述",
        1: "用两到三句话展开说明",
        2: "从一个具体例子切入描述",
        3: "用比喻或类比的方式说明",
    }[variation_idx % 4]
    return (
        f"请就「{topic}」这个话题，{variation}。要求：\n"
        "1. 直接输出内容，不要带标题、编号、markdown 符号\n"
        "2. 内容必须是简体中文，自然流畅的书面语\n"
        "3. 长度控制在 30-100 字之间\n"
        "4. 只输出这一段话，不要分多行，不要任何解释或前言"
    )


def clean_line(text: str) -> str:
    if not text:
        return ""
    # 合并换行
    line = re.sub(r"[\r\n]+", " ", text).strip()
    # 去引号包裹
    line = line.strip('"').strip("「」").strip()
    # 去思考标记
    line = re.sub(r"<think>[\s\S]*?</think>", "", line).strip()
    return line


def gen_one(topic: str, idx: int) -> str | None:
    prompt = make_prompt(topic, idx)
    try:
        resp = client.chat.completions.create(
            model=MODEL,
            messages=[{"role": "user", "content": prompt}],
            temperature=0.85,
            max_tokens=400,
            stream=False,
            extra_body={"chat_template_kwargs": {"enable_thinking": False}},
        )
        text = resp.choices[0].message.content or ""
        return clean_line(text)
    except Exception as e:
        print(f"  [失败] {topic}[{idx}]: {e}", file=sys.stderr)
        return None


def main():
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    tasks = [(t, i) for t in TOPICS for i in range(SAMPLES_PER_TOPIC)]

    # 追加模式：加载已有语料做去重
    seen: set[str] = set()
    existing_lines = 0
    mode = "a" if APPEND and os.path.exists(OUTPUT) else "w"
    if mode == "a":
        with open(OUTPUT, "r", encoding="utf-8") as f:
            for line in f:
                seen.add(line[:40])
                existing_lines += 1
        print(f"追加模式: 已有 {existing_lines} 行, 将生成 {len(tasks)} 条新样本", flush=True)
    else:
        print(f"覆盖模式: 将生成 {len(tasks)} 条新样本", flush=True)

    total = 0
    skipped_dup = 0
    failed = 0
    start = time.time()

    with open(OUTPUT, mode, encoding="utf-8") as f:
        with ThreadPoolExecutor(max_workers=CONCURRENCY) as pool:
            futures = {pool.submit(gen_one, t, i): (t, i) for (t, i) in tasks}
            for n_done, fut in enumerate(as_completed(futures), 1):
                line = fut.result()
                if line and len(line) >= MIN_LEN:
                    if len(line) > MAX_LEN:
                        line = line[:MAX_LEN]
                    key = line[:40]
                    if key in seen:
                        skipped_dup += 1
                        continue
                    seen.add(key)
                    f.write(line + "\n")
                    total += 1
                else:
                    failed += 1
                if n_done % 50 == 0 or n_done == len(tasks):
                    elapsed = time.time() - start
                    print(
                        f"  进度 {n_done}/{len(tasks)}, 新增 {total}, "
                        f"重复 {skipped_dup}, 失败 {failed}, {elapsed:.0f}s",
                        flush=True,
                    )

    elapsed = time.time() - start
    size = os.path.getsize(OUTPUT)
    final_lines = existing_lines + total if mode == "a" else total
    print(f"\n完成! 本次新增 {total} 行, 重复跳过 {skipped_dup}, 失败 {failed}")
    print(f"文件总行数: {final_lines}, {size:,} 字节, 耗时 {elapsed:.0f}s")
    print(f"输出: {OUTPUT}")


if __name__ == "__main__":
    main()
